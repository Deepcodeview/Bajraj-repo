# ─── Agent 5: Daily Store Report Writer ──────────────────────────────────────

@router.post("/shift-report")
def agent5_shift_report(req: ShiftReportReq):
    """Agent 5 — Generates end-of-shift store performance report."""
    a = req.analytics or {}

    entries = a.get("entries", random.randint(180, 420))
    exits   = a.get("exits",   random.randint(160, entries))
    peak    = a.get("peak_crowd", {})
    if isinstance(peak, dict):
        peak_count = peak.get("count", random.randint(30, 80))
    else:
        peak_count = random.randint(30, 80)

    zones = a.get("zones", {})
    zone_counts = zones.get("zone_counts", {
        "Grocery": random.randint(80, 200),
        "Electronics": random.randint(30, 90),
        "Apparel": random.randint(20, 60),
        "Checkout": random.randint(60, 150),
        "Entrance": random.randint(100, 250),
    })

    top_zone  = max(zone_counts, key=zone_counts.get) if zone_counts else "Grocery"
    low_zone  = min(zone_counts, key=zone_counts.get) if zone_counts else "Apparel"
    recs      = random.sample(OPTIMIZER_KB, 3)

    report = SHIFT_REPORT_TEMPLATE.format(
        store=req.store,
        date=datetime.date.today().strftime("%d %b %Y"),
        shift=req.shift,
        entries=entries,
        exits=exits,
        net=max(0, entries - exits),
        peak=peak_count,
        peak_time="6:30 PM",
        top_zone=top_zone,
        top_zone_count=zone_counts.get(top_zone, 0),
        low_zone=low_zone,
        low_zone_count=zone_counts.get(low_zone, 0),
        avg_dwell=round(random.uniform(6, 18), 1),
        shelf_alerts=random.randint(0, 4),
        restocks=random.randint(0, 3),
        critical_alerts=random.randint(0, 2),
        high_alerts=random.randint(1, 5),
        total_alerts=random.randint(3, 10),
        rec1=recs[0],
        rec2=recs[1],
        rec3=recs[2],
    )

    return {
        "agent":   "Daily Store Report Writer",
        "store":   req.store,
        "shift":   req.shift,
        "report":  report,
        "summary": {
            "entries": entries,
            "exits":   exits,
            "peak":    peak_count,
            "top_zone": top_zone,
        },
        "timestamp": datetime.datetime.utcnow().isoformat(),
    }
