# ─── Request Models ───────────────────────────────────────────────────────────

class ZoneInspectReq(BaseModel):
    zone: str
    crowd_count: int
    capacity: int
    job_id: Optional[str] = None

class AlertReq(BaseModel):
    alert_type: str   # crowd_surge | shelf_empty | long_queue | low_conversion
    zone: str
    value: float
    threshold: float
    job_id: Optional[str] = None

class RCAReq(BaseModel):
    issue_type: str   # crowd_surge | shelf_empty | long_queue | low_conversion
    zone: str
    context: Optional[str] = ""

class OptimizeReq(BaseModel):
    job_id: Optional[str] = None
    analytics: Optional[dict] = None

class ShiftReportReq(BaseModel):
    store: str = "Store #1"
    shift: str = "Morning (9AM–5PM)"
    analytics: Optional[dict] = None


# ─── Agent 1: Zone Inspector ──────────────────────────────────────────────────

@router.post("/zone-inspect")
def agent1_zone_inspect(req: ZoneInspectReq):
    """Agent 1 — Analyzes crowd density for a zone."""
    occupancy_pct = (req.crowd_count / max(req.capacity, 1)) * 100
    kb = ZONE_KB.get(req.zone, {"risk": "medium", "tip": "Monitor zone regularly."})

    if occupancy_pct >= 90:
        status = "CRITICAL"
        action = f"Zone '{req.zone}' is at {occupancy_pct:.0f}% capacity. Immediate crowd dispersal needed."
    elif occupancy_pct >= 70:
        status = "WARNING"
        action = f"Zone '{req.zone}' is at {occupancy_pct:.0f}% capacity. Deploy staff to manage flow."
    elif occupancy_pct >= 50:
        status = "MODERATE"
        action = f"Zone '{req.zone}' is moderately busy ({occupancy_pct:.0f}%). Monitor closely."
    else:
        status = "NORMAL"
        action = f"Zone '{req.zone}' is operating normally ({occupancy_pct:.0f}% capacity)."

    return {
        "agent": "Zone Inspector",
        "zone": req.zone,
        "crowd_count": req.crowd_count,
        "capacity": req.capacity,
        "occupancy_pct": round(occupancy_pct, 1),
        "status": status,
        "action": action,
        "tip": kb["tip"],
        "risk_level": kb["risk"],
    }


# ─── Agent 2: Store Alert Manager ────────────────────────────────────────────

@router.post("/store-alert")
def agent2_store_alert(req: AlertReq):
    """Agent 2 — Generates structured alerts with escalation levels."""
    severity = "INFO"
    channels = ["dashboard"]
    escalate = False

    if req.alert_type == "crowd_surge":
        if req.value >= req.threshold * 1.5:
            severity = "CRITICAL"
            channels = ["dashboard", "sms", "email", "slack"]
            escalate = True
        elif req.value >= req.threshold:
            severity = "HIGH"
            channels = ["dashboard", "slack"]

    elif req.alert_type == "shelf_empty":
        severity = "HIGH"
        channels = ["dashboard", "slack", "email"]
        if req.value == 0:
            severity = "CRITICAL"
            escalate = True

    elif req.alert_type == "long_queue":
        if req.value >= 10:
            severity = "CRITICAL"
            channels = ["dashboard", "slack"]
            escalate = True
        elif req.value >= 5:
            severity = "HIGH"
            channels = ["dashboard", "slack"]

    elif req.alert_type == "low_conversion":
        severity = "MEDIUM"
        channels = ["dashboard"]

    messages = {
        "crowd_surge":      f"🚨 Crowd surge in {req.zone}: {int(req.value)} people (threshold: {int(req.threshold)})",
        "shelf_empty":      f"📦 Shelf empty in {req.zone}: stock level {req.value:.0f}% (min: {req.threshold:.0f}%)",
        "long_queue":       f"⏳ Long queue at {req.zone}: {int(req.value)} people waiting",
        "low_conversion":   f"📉 Low conversion in {req.zone}: {req.value:.1f}% (target: {req.threshold:.1f}%)",
    }

    return {
        "agent":      "Store Alert Manager",
        "alert_type": req.alert_type,
        "zone":       req.zone,
        "severity":   severity,
        "message":    messages.get(req.alert_type, f"Alert in {req.zone}"),
        "channels":   channels,
        "escalate":   escalate,
        "timestamp":  datetime.datetime.utcnow().isoformat(),
    }


